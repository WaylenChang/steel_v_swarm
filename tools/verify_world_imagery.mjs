import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {join,resolve} from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {selectWorldBundles} from './world_selection.mjs';
import {worldImagerySource} from './world_imagery_source.mjs';
import {verifyWorldImagery} from './world_imagery_verification.mjs';
import {verifyWorldProvenance} from './world_provenance.mjs';

const root=fileURLToPath(new URL('..',import.meta.url)),[bundle,...extra]=process.argv.slice(2);
if(!bundle||extra.length||!/^[a-zA-Z0-9_]+$/.test(bundle))throw new Error('Select one original imagery bundle');
const source=resolve(process.env.SVS_SOURCE||join(root,'..','steel_vs_swarm'));
const read=async name=>JSON.parse(await readFile(join(root,'data',name),'utf8'));
const [maps,campaign,balance]=await Promise.all([read('maps.json'),read('campaign.json'),read('balance.json')]);
const selected=selectWorldBundles([...maps,...campaign.maps],Object.keys(balance.constants.ENV.seasons),['--bundle='+bundle]).get(bundle);
const directory=join(root,'data/world_imagery'),index=JSON.parse(await readFile(join(directory,bundle+'.json'),'utf8'));
assert.deepEqual(index.identity,{map:selected.map.id,teamSize:selected.size,season:selected.season});
const digest=bytes=>createHash('sha256').update(bytes).digest('hex');
const config=structuredClone(selected.map.variants[String(selected.size)].config);
config.env={...config.env,season:selected.season};
assert.equal(index.configSha256,digest(JSON.stringify(config)),'Original imagery configuration');
const provenance=await verifyWorldProvenance(index,source);
const producers=['tools/capture_world_imagery.mjs','tools/world_imagery_source.mjs','tools/world_imagery_storage.mjs','tools/world_imagery_verification.mjs','tools/source_json.mjs','tools/fixture_json.mjs','tools/world_source_writer.mjs'];
assert.equal(Object.keys(index.source.producer).length,producers.length,'Complete imagery producer identity');
for(const name of producers)assert.equal(digest(await readFile(join(root,name))),index.source.producer[name],'Current imagery producer: '+name);
const {readSrc,grabFn,grabBlock,grabConst}=await import(pathToFileURL(join(source,'tools/audit_src.mjs')).href);
const program=worldImagerySource(readSrc('public','js','terrain.js'),readSrc('public','js','data.js'),grabFn,grabBlock,grabConst);
assert.equal(digest(program),index.source.programSha256,'Current isolated original imagery program');
const result=await verifyWorldImagery(index,directory);
console.log('SOURCE_IMAGERY_STORAGE_PASS '+JSON.stringify({bundle,...result,...provenance}));
